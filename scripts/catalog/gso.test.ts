import { describe, expect, it } from 'vitest';
import { parseObj } from './gso';

// A quad lying on the floor, in the form of GSO's model.obj: +Z up, faces of v/vt/vn corners.
const QUAD = `# Generated by Katamari OBJ encoder.
mtllib model.mtl
v 0 0 0
v 0.1 0 0
v 0.1 0.2 0
v 0 0.2 0
vt 0 0
vt 1 0
vt 1 1
vt 0 1
vn 0 0 1
usemtl material_0
f 1/1/1 2/2/1 3/3/1 4/4/1
`;

describe('parseObj', () => {
  const mesh = parseObj(QUAD);

  it('turns +Z up into +Y up: (x, y, z) → (x, z, −y)', () => {
    expect(Array.from(mesh.positions, (v) => +v.toFixed(6))).toEqual([0, 0, 0, 0.1, 0, 0, 0.1, 0, -0.2, 0, 0, -0.2]);
    expect([...mesh.normals.slice(0, 3)]).toEqual([0, 1, -0]);
  });

  it("flips v, since OBJ's runs up the image and glTF's down", () => {
    expect([...mesh.uvs]).toEqual([0, 1, 1, 1, 1, 0, 0, 0]);
  });

  it('fans a face of more than three corners into triangles', () => {
    expect([...mesh.indices]).toEqual([0, 1, 2, 0, 2, 3]);
  });

  it('shares a corner that several faces use', () => {
    const twice = parseObj(QUAD.replace('f 1/1/1 2/2/1 3/3/1 4/4/1', 'f 1/1/1 2/2/1 3/3/1\nf 1/1/1 3/3/1 4/4/1'));
    expect(twice.positions.length / 3).toBe(4);
    expect([...twice.indices]).toEqual([0, 1, 2, 0, 2, 3]);
  });

  it('rejects a face corner without a uv or a normal', () => {
    expect(() => parseObj(QUAD.replace('f 1/1/1', 'f 1//1'))).toThrow(/v\/vt\/vn/);
  });
});
